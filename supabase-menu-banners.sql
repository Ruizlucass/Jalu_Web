-- Ejecutar una vez en Supabase SQL Editor para habilitar el carrusel de imágenes del menú.

create table if not exists public.banners_menu (
  id bigint generated by default as identity primary key,
  imagen_url text not null unique,
  fecha_inicio timestamptz,
  fecha_limite timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.banners_menu
  add column if not exists fecha_inicio timestamptz;
alter table public.banners_menu
  add column if not exists fecha_limite timestamptz;

-- Si la tabla ya existía, recupera las fechas de la promoción original.
update public.banners_menu as banner
set fecha_inicio = promociones.fecha_inicio
from (
  select imagen_url, min(fecha_inicio) as fecha_inicio
  from public.promociones
  where nullif(trim(imagen_url), '') is not null
  group by imagen_url
) as promociones
where banner.imagen_url = promociones.imagen_url
  and banner.fecha_inicio is null;

update public.banners_menu as banner
set fecha_limite = promociones.fecha_limite
from (
  select imagen_url, max(fecha_fin) as fecha_limite
  from public.promociones
  where nullif(trim(imagen_url), '') is not null
  group by imagen_url
) as promociones
where banner.imagen_url = promociones.imagen_url
  and banner.fecha_limite is null;

update public.banners_menu
set fecha_inicio = now()
where fecha_inicio is null;

update public.banners_menu
set fecha_limite = now() + interval '7 days'
where fecha_limite is null;

alter table public.banners_menu
  alter column fecha_inicio set default now(),
  alter column fecha_inicio set not null,
  alter column fecha_limite set default (now() + interval '7 days'),
  alter column fecha_limite set not null;

-- Conserva en el carrusel las imágenes que ya estaban cargadas en promociones.
insert into public.banners_menu (imagen_url, fecha_inicio, fecha_limite, created_at, updated_at)
select imagen_url, min(fecha_inicio), max(fecha_fin), min(created_at), max(updated_at)
from public.promociones
where activa = true
  and fecha_inicio <= now()
  and fecha_fin > now()
  and nullif(trim(imagen_url), '') is not null
group by imagen_url
on conflict (imagen_url) do nothing;

create or replace function public.current_user_role_name()
returns text
language sql
security definer
set search_path = public
stable
as $$
  select r.nombre
  from public.profiles p
  join public.roles r on r.id = p.role_id
  where p.id = auth.uid()
  limit 1
$$;

grant execute on function public.current_user_role_name() to authenticated;
grant select on public.banners_menu to anon, authenticated;
grant insert, update, delete on public.banners_menu to authenticated;
grant usage, select on sequence public.banners_menu_id_seq to authenticated;

alter table public.banners_menu enable row level security;

drop policy if exists "banners_menu_public_select" on public.banners_menu;
create policy "banners_menu_public_select"
on public.banners_menu
for select
to anon, authenticated
using (true);

drop policy if exists "banners_menu_admin_insert" on public.banners_menu;
create policy "banners_menu_admin_insert"
on public.banners_menu
for insert
to authenticated
with check (public.current_user_role_name() in ('admin', 'superadmin'));

drop policy if exists "banners_menu_admin_update" on public.banners_menu;
create policy "banners_menu_admin_update"
on public.banners_menu
for update
to authenticated
using (public.current_user_role_name() in ('admin', 'superadmin'))
with check (public.current_user_role_name() in ('admin', 'superadmin'));

drop policy if exists "banners_menu_admin_delete" on public.banners_menu;
create policy "banners_menu_admin_delete"
on public.banners_menu
for delete
to authenticated
using (public.current_user_role_name() in ('admin', 'superadmin'));
