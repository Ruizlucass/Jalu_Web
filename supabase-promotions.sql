create table if not exists public.promociones (
  id bigint generated by default as identity primary key,
  titulo text not null,
  descripcion text not null default '',
  tipo_descuento text not null
    check (tipo_descuento in ('porcentaje', 'monto_fijo')),
  valor_descuento numeric(10, 2) not null check (valor_descuento > 0),
  fecha_inicio timestamptz not null,
  fecha_fin timestamptz not null,
  aplica_todas_sucursales boolean not null default true,
  sucursales_aplicables text[] not null default '{}',
  activa boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint promociones_fechas_validas check (fecha_fin > fecha_inicio),
  constraint promociones_sucursales_validas check (
    (aplica_todas_sucursales and cardinality(sucursales_aplicables) = 0)
    or
    (not aplica_todas_sucursales and cardinality(sucursales_aplicables) > 0)
  ),
  constraint promociones_porcentaje_valido
    check (tipo_descuento <> 'porcentaje' or valor_descuento <= 100)
);

-- Actualiza instalaciones que ya tenían creada la tabla antes del selector de sucursales.
alter table public.promociones
  add column if not exists aplica_todas_sucursales boolean not null default true;
alter table public.promociones
  add column if not exists sucursales_aplicables text[] not null default '{}';
alter table public.promociones
  drop constraint if exists promociones_sucursales_validas;
alter table public.promociones
  add constraint promociones_sucursales_validas check (
    (aplica_todas_sucursales and cardinality(sucursales_aplicables) = 0)
    or
    (not aplica_todas_sucursales and cardinality(sucursales_aplicables) > 0)
  );

create or replace function public.current_user_role_name()
returns text
language sql
security definer
set search_path = public
stable
as $$
  select r.nombre
  from public.profiles p
  join public.roles r on r.id = p.role_id
  where p.id = auth.uid()
  limit 1
$$;

grant execute on function public.current_user_role_name() to authenticated;
grant select on public.promociones to anon, authenticated;
grant insert, update, delete on public.promociones to authenticated;
grant usage, select on sequence public.promociones_id_seq to authenticated;

alter table public.promociones enable row level security;

drop policy if exists "promociones_public_select_active" on public.promociones;
create policy "promociones_public_select_active"
on public.promociones
for select
to anon, authenticated
using (
  activa = true
  and fecha_inicio <= now()
  and fecha_fin > now()
);

drop policy if exists "promociones_admin_select" on public.promociones;
create policy "promociones_admin_select"
on public.promociones
for select
to authenticated
using (public.current_user_role_name() in ('admin', 'superadmin'));

drop policy if exists "promociones_admin_insert" on public.promociones;
create policy "promociones_admin_insert"
on public.promociones
for insert
to authenticated
with check (public.current_user_role_name() in ('admin', 'superadmin'));

drop policy if exists "promociones_admin_update" on public.promociones;
create policy "promociones_admin_update"
on public.promociones
for update
to authenticated
using (public.current_user_role_name() in ('admin', 'superadmin'))
with check (public.current_user_role_name() in ('admin', 'superadmin'));

drop policy if exists "promociones_admin_delete" on public.promociones;
create policy "promociones_admin_delete"
on public.promociones
for delete
to authenticated
using (public.current_user_role_name() in ('admin', 'superadmin'));
